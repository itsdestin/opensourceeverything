// Writes mockups/map-data.js (window.MAP) from data/*.json so the clickable demos show the real map.
// WHY a script file, not fetch(): the demos open straight from disk (file://), where browsers block fetch.
// Run: node prefill/make-demo-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const MAP = {
  categories: read('data/categories.json').categories,
  groups: read('data/groups.json').groups.map((g) => ({ id: g.id, name: g.name, category: g.category, job: g.job, closed: g.closed,
    alternatives: g.alternatives.map((a) => ({ project: a.project, fit: a.fit, note: a.note })) })),
  projects: read('data/projects.json').projects.map((p) => ({ id: p.id, name: p.name, summary: p.summary, kind: p.kind, code: p.code, website: p.website,
    license: p.license, licenseClass: p.licenseClass, stars: p.stars, inactive: p.inactive, source: p.source })),
  // Projects set aside because no group covers their closed app: they seed the mod page's Suggestions tab.
  unplaced: read('prefill/out/unplaced.json'),
};
writeFileSync(join(ROOT, 'mockups/map-data.js'), `// Generated by prefill/make-demo-data.mjs from data/*.json. Do not edit.\nwindow.MAP = ${JSON.stringify(MAP)};\n`);
console.log(`map-data.js: ${MAP.groups.length} groups, ${MAP.projects.length} projects, ${MAP.unplaced.length} unplaced`);
